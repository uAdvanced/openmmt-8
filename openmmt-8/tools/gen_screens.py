#!/usr/bin/env python3
"""Generate the screen tables (build/core/screens.h) from core/screens.def.

Templates are packed: a byte below 0x20 stands for that many spaces, and trailing spaces
are dropped (the display is cleared first). The packed bytes are then byte-pair coded.
A byte >= 0x80 is a pair in tpl_dict; ui_screen expands pairs before the space-run rule.
Pairs never cross a screen boundary, and expansion nests at most 8 pending bytes.
"""
import os
import re
import sys
from collections import Counter

src, dst = sys.argv[1], sys.argv[2]
# ".if NAME" / ".if !NAME" ... ".endif" keep rows for builds with (without) -DOPENMMT8_NAME
# in OPENMMT8_CFLAGS.
defines = set(re.findall(r"-DOPENMMT8_(\w+)", os.environ.get("OPENMMT8_CFLAGS", "")))
rows, keep = [], [True]
for line in open(src):
    m = re.match(r"\.if\s+(!?)(\w+)\s*$", line)
    if m:
        keep.append(keep[-1] and ((m.group(2) in defines) != bool(m.group(1))))
        continue
    if re.match(r"\.endif\s*$", line):
        keep.pop()
        continue
    if not keep[-1]:
        continue
    if line.strip() and not line.startswith("#"):
        m = re.match(r'(\w+)\s+"(.{16})"\s+"(.{16})"\s+(\d+)\s+(\d+)\s+(\d+)\s*$', line.rstrip("\n"))
        if not m:
            sys.exit(f"{src}: bad line: {line.rstrip()}")
        rows.append(m.groups())

def pack(text):
    text, out, i = text.rstrip(), [], 0
    while i < len(text):
        j = i
        while j < len(text) and text[j] == " ":
            j += 1
        if j - i > 1:
            out.append(j - i)
            i = j
        else:
            out.append(ord(text[i]))
            i += 1
    return out

plain = []
for _, l1, l2, *_ in rows:
    text = (l1 + l2).rstrip()
    plain.append(text + " " * (32 - len(text)))
packed = [bytearray(pack(p)) for p in plain]

def expand(src_bytes, flat):
    """Same steps as ui_screen. Returns the 32 chars and the deepest pending-byte count."""
    n, si, stk, k, out, deepest = len(src_bytes), 0, [], 0, [], 0
    while len(out) < 32:
        c = 0x20
        if k:
            k -= 1
        else:
            if stk:
                c = stk.pop()
            elif n:
                n -= 1
                c = src_bytes[si]
                si += 1
            while c >= 0x80:
                ix = (c - 0x80) * 2
                stk.append(flat[ix + 1])
                c = flat[ix]
                deepest = max(deepest, len(stk))
            if c < 0x20:
                k = c - 1
                c = 0x20
        out.append(c)
    return bytes(out), deepest

for raw, text in zip(packed, plain):
    got, _ = expand(raw, b"")
    if got != text.encode():
        sys.exit("pack/expand mismatch before dictionary coding")

dictionary = []
while len(dictionary) < 96:
    pairs = Counter()
    for s in packed:
        for i in range(len(s) - 1):
            pairs[(s[i], s[i + 1])] += 1
    chosen = None
    best_nov = 2
    for (a, b), _ in pairs.most_common(40):
        nov = 0
        for s in packed:
            i = 0
            while i < len(s) - 1:
                if s[i] == a and s[i + 1] == b:
                    nov += 1
                    i += 2
                else:
                    i += 1
        if nov <= best_nov:
            continue
        tok = 0x80 + len(dictionary)
        trial = []
        for s in packed:
            o, i = bytearray(), 0
            while i < len(s):
                if i < len(s) - 1 and s[i] == a and s[i + 1] == b:
                    o.append(tok)
                    i += 2
                else:
                    o.append(s[i])
                    i += 1
            trial.append(o)
        flat = b"".join(bytes(p) for p in dictionary) + bytes((a, b))
        if all(expand(s, flat)[1] <= 8 for s in trial):
            chosen = (trial, (a, b))
            best_nov = nov
    if chosen is None:
        break
    packed, pair = chosen
    dictionary.append(pair)

flat = b"".join(bytes(p) for p in dictionary)
for src_bytes, text in zip(packed, plain):
    got, deep = expand(src_bytes, flat)
    if got != text.encode() or deep > 8:
        sys.exit("dictionary expansion does not match the screen text")

raw_n = sum(len(pack(p)) for p in plain)
print(f"screens: {raw_n} packed bytes -> {sum(len(s) for s in packed)} + {len(flat)} dict", file=sys.stderr)

with open(dst, "w") as f:
    f.write("/* Generated by tools/gen_screens.py from core/screens.def. */\n")
    f.write("enum {\n" + "".join(f"    T_{r[0]},\n" for r in rows) + "};\n\n")
    f.write("static const uint8_t __code tpl_len[] = {" + ", ".join(str(len(p)) for p in packed) + "};\n")
    f.write("static const uint8_t __code tpl_dict[] = {\n    " + ", ".join(f"0x{b:02X}" for b in flat) + "\n};\n")
    f.write("static const uint8_t __code tpl_z[] = {\n")
    for r, p in zip(rows, packed):
        body = ", ".join(f"0x{b:02X}" for b in p) if p else ""
        f.write(f"    {body}, /* {r[0]} */\n" if body else f"    /* {r[0]} */\n")
    f.write("};\n")
    f.write("static const uint8_t __code tpl_pass[][3] = {\n")
    f.write("".join(f"    {{{r[3]}, {r[4]}, {r[5]}}},\n" for r in rows) + "};\n")
